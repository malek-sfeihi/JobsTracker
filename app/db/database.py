"""Database access. Works with a local SQLite file or an online PostgreSQL database.

The rest of the app writes plain SQL with "?" placeholders and reads rows by column name
(row["subject"]), as with sqlite3. Underneath, SQLAlchemy translates for the actual database,
so the same queries run on SQLite (your PC) and PostgreSQL (online).
"""
import re
from datetime import datetime, timezone
from functools import lru_cache

from sqlalchemy import Engine, create_engine, inspect, text

from app.core.config import settings


def _schema(dialect: str) -> list[str]:
    # The only real difference between the two: how an auto-numbered id is declared
    auto_id = ("INTEGER PRIMARY KEY AUTOINCREMENT" if dialect == "sqlite"
               else "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    return [
        # One row per downloaded email. We keep the raw content (subject, body...) so that when
        # the rules improve we can re-classify everything without downloading from Gmail again.
        """CREATE TABLE IF NOT EXISTS emails (
            id          TEXT PRIMARY KEY,   -- Gmail message id
            thread_id   TEXT NOT NULL,
            sender      TEXT NOT NULL,
            subject     TEXT NOT NULL,
            received_at TEXT NOT NULL,      -- ISO date, e.g. 2026-09-23T14:02:11+00:00
            body        TEXT NOT NULL,
            category    TEXT,               -- confirmation / rejection / ... or NULL if not a job email
            kind        TEXT                -- job / program
        )""",
        # One row per application (company + position), built from the emails above.
        f"""CREATE TABLE IF NOT EXISTS applications (
            id       {auto_id},
            company  TEXT NOT NULL,
            position TEXT,                  -- NULL when no email mentions the job title
            kind     TEXT NOT NULL,
            status   TEXT,                  -- action_needed / in_progress / ghosted / expired / rejected / offer
            last_activity TEXT,             -- date of the most recent email
            first_activity TEXT,            -- date of the first email (~ when you applied)
            anchor_email_id TEXT,           -- id of the first email: stable across rebuilds, unlike `id`
            rejection_reason TEXT,          -- why they said no (see app/filters/reasons.py)
            rejection_quote TEXT            -- the sentence of the email that says it
        )""",
        # Your hand labels: the "gold" ground truth that both the rules and the ML model are
        # measured against. Never rebuilt or overwritten by the code, only by you.
        """CREATE TABLE IF NOT EXISTS labels (
            email_id   TEXT PRIMARY KEY REFERENCES emails(id),
            label      TEXT NOT NULL,       -- confirmation / rejection / assessment / interview / offer / not_job
            labeled_at TEXT NOT NULL
        )""",
        # One row per sync run, so the dashboard can say "synced at 07:00" or warn if it failed.
        """CREATE TABLE IF NOT EXISTS sync_runs (
            ran_at     TEXT NOT NULL,
            new_emails INTEGER,
            ok         INTEGER NOT NULL,    -- 1 = success, 0 = failure
            message    TEXT
        )""",
        # Your manual corrections from the dashboard. Applications are rebuilt from scratch on
        # every sync, so corrections live here and are re-applied each time (NULL = no correction).
        """CREATE TABLE IF NOT EXISTS overrides (
            anchor_email_id TEXT PRIMARY KEY,
            company  TEXT,
            position TEXT,
            status   TEXT
        )""",
    ]


# Columns added after the first version: older databases get them on the next start
_MIGRATIONS = [
    ("emails", "application_id", "INTEGER REFERENCES applications(id)"),
    ("applications", "status", "TEXT"),
    ("applications", "last_activity", "TEXT"),
    ("applications", "first_activity", "TEXT"),
    ("applications", "anchor_email_id", "TEXT"),
    ("applications", "rejection_reason", "TEXT"),
    ("applications", "rejection_quote", "TEXT"),
]


def database_url() -> str:
    url = settings.database_url
    if not url:
        return f"sqlite:///{settings.db_path}"
    # Hosting services give "postgresql://..."; SQLAlchemy needs to know which driver to use
    return re.sub(r"^postgres(ql)?://", "postgresql+psycopg://", url)


@lru_cache
def _engine(url: str) -> Engine:
    """One engine (= pool of connections) per database, created on first use."""
    engine = create_engine(url, pool_pre_ping=True)  # pre_ping: reconnect if the server closed the link
    with engine.begin() as conn:  # create tables + migrations once per process, not per query
        for statement in _schema(engine.dialect.name):
            conn.execute(text(statement))
        existing = {table: {c["name"] for c in inspect(conn).get_columns(table)}
                    for table in {t for t, _, _ in _MIGRATIONS}}
        for table, column, definition in _MIGRATIONS:
            if column not in existing[table]:
                conn.execute(text(f"ALTER TABLE {table} ADD COLUMN {column} {definition}"))
    return engine


class Row(dict):
    """A result row, readable by column name (row["subject"]) or position (row[0])."""

    def __getitem__(self, key):
        if isinstance(key, int):
            return list(self.values())[key]
        return super().__getitem__(key)


class Result:
    def __init__(self, rows: list[Row]):
        self._rows = rows

    def fetchall(self) -> list[Row]:
        return self._rows

    def fetchone(self) -> Row | None:
        return self._rows[0] if self._rows else None

    def __iter__(self):
        return iter(self._rows)


def _named(sql: str, params) -> tuple[str, dict]:
    """"WHERE id = ? AND x = ?" + (1, 2) -> "WHERE id = :p0 AND x = :p1" + {"p0": 1, "p1": 2}."""
    parts = sql.split("?")
    named_sql = parts[0] + "".join(f":p{i}{part}" for i, part in enumerate(parts[1:]))
    return named_sql, {f"p{i}": value for i, value in enumerate(params)}


class Connection:
    """Same small interface as sqlite3.Connection, for SQLite and PostgreSQL alike."""

    def __init__(self, engine: Engine):
        self.sqlalchemy = engine.connect()  # also usable directly, e.g. pd.read_sql(sql, conn.sqlalchemy)

    def execute(self, sql: str, params=()) -> Result:
        named_sql, values = _named(sql, params)
        result = self.sqlalchemy.execute(text(named_sql), values)
        return Result([Row(m) for m in result.mappings()] if result.returns_rows else [])

    def executemany(self, sql: str, seq_of_params) -> None:
        rows = [_named(sql, params) for params in seq_of_params]
        if rows:
            self.sqlalchemy.execute(text(rows[0][0]), [values for _, values in rows])

    def commit(self) -> None:
        self.sqlalchemy.commit()

    def close(self) -> None:
        self.sqlalchemy.close()


def get_connection() -> Connection:
    return Connection(_engine(database_url()))


def close_all() -> None:
    """Close every open database link (needed before deleting a SQLite file on Windows)."""
    if _engine.cache_info().currsize:
        _engine(database_url()).dispose()
    _engine.cache_clear()


def save_label(conn: Connection, email_id: str, label: str) -> None:
    conn.execute(
        """INSERT INTO labels (email_id, label, labeled_at) VALUES (?, ?, ?)
           ON CONFLICT(email_id) DO UPDATE SET label = excluded.label, labeled_at = excluded.labeled_at""",
        (email_id, label, datetime.now(timezone.utc).isoformat()),
    )
    conn.commit()


def record_sync_run(conn: Connection, new_emails: int | None, ok: bool, message: str = "") -> None:
    conn.execute(
        "INSERT INTO sync_runs (ran_at, new_emails, ok, message) VALUES (?, ?, ?, ?)",
        (datetime.now(timezone.utc).isoformat(), new_emails, int(ok), message),
    )
    conn.commit()


def save_override(conn: Connection, anchor_email_id: str, company: str | None,
                  position: str | None, status: str | None) -> None:
    # "Upsert": insert, or if a correction already exists, only overwrite the fields given now
    # (NULL keeps the previous correction - renaming today won't erase yesterday's status fix)
    conn.execute(
        """INSERT INTO overrides (anchor_email_id, company, position, status) VALUES (?, ?, ?, ?)
           ON CONFLICT(anchor_email_id) DO UPDATE SET
               company  = COALESCE(excluded.company, overrides.company),
               position = COALESCE(excluded.position, overrides.position),
               status   = COALESCE(excluded.status, overrides.status)""",
        (anchor_email_id, company, position, status),
    )


def known_email_ids(conn: Connection) -> set[str]:
    return {row["id"] for row in conn.execute("SELECT id FROM emails")}


def save_email(conn: Connection, email: dict, category: str | None, kind: str) -> None:
    # The "?" placeholders insert the values safely (never build SQL with f-strings: an email
    # subject containing a quote would break the query, or worse - SQL injection)
    conn.execute(
        """INSERT INTO emails (id, thread_id, sender, subject, received_at, body, category, kind)
           VALUES (?, ?, ?, ?, ?, ?, ?, ?)
           ON CONFLICT(id) DO UPDATE SET
               thread_id = excluded.thread_id, sender = excluded.sender, subject = excluded.subject,
               received_at = excluded.received_at, body = excluded.body,
               category = excluded.category, kind = excluded.kind""",
        (email["id"], email["thread_id"], email["sender"], email["subject"],
         email["received_at"], email["body"], category, kind),
    )
